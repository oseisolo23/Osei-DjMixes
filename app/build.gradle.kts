  signingConfigs {
    create("release") {
      val keystoreFile = project.rootProject.file("key.properties")
      if (keystoreFile.exists()) {
          val properties = Properties()
          properties.load(FileInputStream(keystoreFile))
          val storeFilePath = properties.getProperty("storeFile")
          if (storeFilePath != null) {
              storeFile = project.rootProject.file(storeFilePath)
          }
          storePassword = properties.getProperty("storePassword")
          keyAlias = properties.getProperty("keyAlias")
          keyPassword = properties.getProperty("keyPassword")
      } else {
          val keystorePath = System.getenv("KEYSTORE_PATH")
          if (keystorePath != null) {
              storeFile = file(keystorePath)
              storePassword = System.getenv("STORE_PASSWORD")
              keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
              keyPassword = System.getenv("KEY_PASSWORD")
          } else {
              val uploadKey = project.rootProject.file("my-upload-key.jks")
              if (uploadKey.exists()) {
                  storeFile = uploadKey
                  storePassword = System.getenv("STORE_PASSWORD")
                  keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
                  keyPassword = System.getenv("KEY_PASSWORD")
              }
          }
      }
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
